import 'store_listing.dart';
import 'store_vendor.dart';

/// متن‌های وابسته به فروشگاه، به‌صورت متمرکز و امن.
///
/// هر بیلد فقط درگاه فروشگاه خودش را دارد؛ پس نامی که در پی‌وال و وضعیت
/// خرید به والد نشان داده می‌شود باید همان فروشگاه نصب‌کننده باشد. این
/// کلاس اجازه نمی‌دهد نام یک فروشگاه به‌صورت رشتهٔ ثابت در صفحه‌های UI
/// تکرار شود (و مثلاً در بیلد کافه‌بازار، «مایکت» چاپ شود).
///
/// تا وقتی تشخیص فروشگاه تمام نشده است، متن‌ها از واژهٔ عمومی «فروشگاه»
/// استفاده می‌کنند؛ این حالت فقط چند میلی‌ثانیهٔ ابتدای اجرا یا محیط تست
/// بدون پلاگین نیتیو را پوشش می‌دهد.
abstract final class StorePolicy {
  /// قبل از نمایش متن وابسته به فروشگاه صدا زده می‌شود تا نام درست
  /// («کافه‌بازار» یا «مایکت») در همان اولین فریم آماده باشد.
  static Future<void> ensureResolved() async {
    if (StoreDetector.cached == null) await StoreDetector.detect();
  }

  /// نام نمایشی فروشگاه نصب‌کننده، یا رشتهٔ خالی اگر هنوز ناشناخته است.
  static String get _name => StoreListing.displayName(StoreDetector.lastKnown);

  static bool get _known => _name.isNotEmpty;

  /// «کافه‌بازار» / «مایکت» / «فروشگاه»
  static String get storeName => _known ? _name : 'فروشگاه';

  /// برچسب کنار مبلغ در کارت قیمت پی‌وال.
  static String get paymentMethodLabel =>
      _known ? 'در پرداخت $_name' : 'در پنجرهٔ پرداخت فروشگاه';

  /// متن جایگزین عدد قیمت؛ مبلغ نهایی همیشه در پنجرهٔ خود فروشگاه دیده
  /// می‌شود و در برنامه hard-code نمی‌شود.
  static String get finalPriceNotice => _known
      ? 'مبلغ نهایی را $_name در پنجرهٔ پرداخت نشان می‌دهد.'
      : 'مبلغ نهایی را فروشگاه در پنجرهٔ پرداخت نشان می‌دهد.';

  /// پیام بیلد غیررسمی (debug/test-only/نصب دستی بدون فروشگاه).
  static String get untrustedBuildNotice => _known
      ? 'فعال‌سازی فقط در نسخهٔ رسمی انتشار $_name امکان‌پذیر است.'
      : 'فعال‌سازی فقط در نسخهٔ رسمی انتشار فروشگاه امکان‌پذیر است.';

  static String get receiptVerifiedNotice => _known
      ? 'نسخهٔ کامل؛ رسید امضاشدهٔ $_name تأیید شد.'
      : 'نسخهٔ کامل؛ رسید امضاشدهٔ فروشگاه تأیید شد.';

  static String get offlineReceiptVerifiedNotice => _known
      ? 'نسخهٔ کامل آفلاین؛ امضای رسید $_name ذخیره‌شده تأیید شد.'
      : 'نسخهٔ کامل آفلاین؛ امضای رسید فروشگاه ذخیره‌شده تأیید شد.';
}
