def audit() -> int:
    """گزارش می‌دهد که آیا متنِ ضبطِ الفبا هنوز حرف عربی‌زا دارد یا نه."""
    problems = 0
    for key, (letter, phrase, word) in LETTERS.items():
        hits = {ch for ch in phrase if ch in FORBIDDEN_IN_TTS_INPUT}
        if hits:
            print(f"✗ {key} ({letter}): متن ضبط شامل {sorted(hits)} → «{phrase}»")
            problems += 1
    if problems == 0:
        print(f"✓ هر {len(LETTERS)} جملهٔ الفبا عاری از حروف عربی‌زا است.")
    return problems


